import { createCanvas, loadImage } from '@napi-rs/canvas';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const svg = (await readFile('docs/icon.svg', 'utf8')).replace('<svg ', '<svg width="256" height="256" ');
const canvas = createCanvas(256, 256);
canvas.getContext('2d').drawImage(await loadImage(Buffer.from(svg)), 0, 0, 256, 256);
const png = canvas.toBuffer('image/png');
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18);
await mkdir('desktop/assets', { recursive: true });
await writeFile('desktop/assets/icon.ico', Buffer.concat([header, png]));
